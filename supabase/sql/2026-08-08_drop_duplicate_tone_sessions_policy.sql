-- ✅ ต้องเหลือ SELECT policy เดียวสำหรับ tone_sessions คือ "select own sessions"
--    (ยังต้องเห็น "insert own sessions" อยู่ด้วย เพราะเป็นคนละคำสั่ง ไม่เกี่ยวกับงานนี้)
select policyname, cmd, qual
from pg_policies
where tablename = 'tone_sessions'
order by cmd, policyname;

-- ✅ ต้องได้ 0 แถว — ยืนยันว่า "read own sessions" หายไปแล้วจริง
select policyname
from pg_policies
where tablename = 'tone_sessions'
  and policyname = 'read own sessions';

