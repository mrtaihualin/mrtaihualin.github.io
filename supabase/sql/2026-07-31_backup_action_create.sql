-- ────────────────────────────────────────────────────────────────────────────
-- ขั้นที่ 1 — เช็คก่อนว่ามีด่านจำกัดค่าอยู่ไหม  (วางแล้วกด Run)
-- ────────────────────────────────────────────────────────────────────────────
-- ได้ 0 แถว  = ไม่มีด่าน → ✅ ไม่ต้องทำอะไรต่อ ปุ่มคืนค่าใช้ได้เลย จบ
-- ได้ 1 แถว  = มีด่าน → อ่านช่อง "เงื่อนไขที่ตั้งไว้" ว่ามีคำว่า 'create' อยู่ในนั้นไหม
--                มี   → ✅ ไม่ต้องทำอะไรต่อ จบ
--                ไม่มี → ไปขั้นที่ 2

select con.conname                          as ชื่อด่าน,
       pg_get_constraintdef(con.oid)        as เงื่อนไขที่ตั้งไว้
from pg_constraint con
join pg_class rel on rel.oid = con.conrelid
join pg_namespace nsp on nsp.oid = rel.relnamespace
where nsp.nspname = 'public'
  and rel.relname = 'classroom_calendar_backups'
  and con.contype = 'c'
  and pg_get_constraintdef(con.oid) ilike '%action%';


-- ────────────────────────────────────────────────────────────────────────────
-- ขั้นที่ 2 — เฉพาะกรณีขั้นที่ 1 เจอด่านที่ไม่มีคำว่า 'create'
-- ────────────────────────────────────────────────────────────────────────────
-- ⚠️ เอา "ชื่อด่าน" ที่ได้จากขั้นที่ 1 มาแทนตรง ชื่อด่านที่ได้จากขั้นที่1 ทั้ง 2 จุด
-- ⚠️ แล้วเอา "เงื่อนไขที่ตั้งไว้" จากขั้นที่ 1 มาดูว่ามีค่าอะไรอยู่บ้าง เผื่อมีค่าที่ไฟล์นี้ไม่รู้จัก
--    (ตอนเขียนไฟล์นี้ โค้ดเว็บใช้อยู่ 5 ค่า: move / delete / permanent_change / archive_student / create)
--    ถ้าของจริงมีค่าอื่นเพิ่ม ต้องใส่เข้าไปในรายการข้างล่างด้วย ไม่งั้นของเดิมจะพัง

