-- ── [A] เพิ่มช่อง "ถูกลบเมื่อไหร่" ────────────────────────────────────────
-- null      = คำนี้ยังอยู่ในคลังของผู้ใช้ (ค่าเริ่มต้นของทุกแถวเดิม — ถูกต้องแล้ว ไม่ต้องแก้ย้อนหลัง)
-- ไม่ null  = เจ้าของสั่งลบคำนี้เมื่อเวลานั้น (ตรา/tombstone) เครื่องอื่นเห็นแล้วลบตามได้
alter table public.learning_saved_items
  add column if not exists deleted_at timestamptz;

comment on column public.learning_saved_items.deleted_at is
  'null = คำยังอยู่ในคลัง · ไม่ null = เจ้าของสั่งลบเมื่อเวลานั้น (tombstone ให้เครื่องอื่นลบตาม) — ห้ามลบแถวทิ้งจริงจากฝั่ง client เพราะ "ไม่มีแถว" ต้องไม่ถูกแปลว่า "ถูกลบ"';


-- ── [B] index ให้การ sync อ่านเร็ว (อ่านทั้งคำที่ใช้อยู่และตราที่ถูกลบ ในคำสั่งเดียว) ──
create index if not exists idx_lsi_user_vault
  on public.learning_saved_items(user_id, vault_key);


-- ── [C] จดว่าไฟล์นี้ถูกรันแล้ว (ข้ามให้เองถ้าฐานข้อมูลนี้ยังไม่มีระบบติดตาม migration) ──
