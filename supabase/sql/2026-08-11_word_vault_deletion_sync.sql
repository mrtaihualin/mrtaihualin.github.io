-- 2026-08-11 — คลังคำ: ทำให้ "ผู้ใช้ลบคำ" ตามไปทุกเครื่องได้จริง (deletion tombstone)
-- ────────────────────────────────────────────────────────────────────────────
-- ต่อจาก: supabase/sql/2026-08-11_learning_foundation.sql (สร้างตาราง learning_saved_items)
-- คู่กับ:  js/games/word-vault.js · scripts/tests-word-vault-sync.js
--          supabase/tests/2026-08-11_word_vault_sync_TEST.sql
--
-- ปัญหาที่แก้ (อธิบายแบบภาษาคน):
--   เดิมเวลาผู้ใช้ลบคำที่เครื่อง A ระบบลบแถวออกจากเซิร์ฟเวอร์จริง
--   แต่เครื่อง B ที่ยังมีคำนั้นค้างอยู่ **มองไม่ออกว่า "หายไปเพราะเจ้าของลบ" หรือ "อ่านมาไม่ครบ"**
--   → เลยต้องเลือกทางปลอดภัยไว้ก่อน คือเก็บคำไว้ = เครื่อง B ยังเห็นคำที่ลบแล้ว
--
-- วิธีแก้: เปลี่ยนจาก "ลบแถวทิ้ง" เป็น "ปั๊มตราว่าถูกลบเมื่อไหร่" (soft delete / tombstone)
--   แถวยังอยู่ แต่มี deleted_at ติดไว้ → เครื่องอื่นเห็นตราชัดเจนว่า **เจ้าของสั่งลบจริง**
--
-- 🔑 หลักความปลอดภัยที่ได้มา (สำคัญที่สุดของไฟล์นี้):
--   **"ไม่มีแถวบนเซิร์ฟเวอร์" ห้ามแปลว่า "ถูกลบ" อีกต่อไป**
--   ลบข้อมูลในเครื่องได้ต่อเมื่อ **เห็นตรา deleted_at ชัดเจน** เท่านั้น
--   → แยก 4 สถานการณ์ออกจากกันได้เองโดยไม่ต้องเดา:
--     1. เจ้าของสั่งลบจริง      → มีแถว + deleted_at ไม่ว่าง  → ลบในเครื่องได้
--     2. เซิร์ฟเวอร์ยังไม่มีข้อมูล → ไม่มีแถวเลย                → เก็บของในเครื่องไว้ + ส่งขึ้น
--     3. อ่านมาไม่ครบ            → แถวบางส่วนหายไป             → เก็บของในเครื่องไว้ (ไม่ลบ)
--     4. เน็ตหลุด/อ่านพลาด        → คำสั่ง select ตอบ error      → ไม่แตะอะไรเลย
--
-- ✅ ความปลอดภัยของไฟล์นี้:
--   · **ไม่มีคำสั่งลบข้อมูลเลย** (มีแค่ `alter table ... add column if not exists` + สร้าง index)
--     → ตามกฎ repo ข้อ 6 ไฟล์ที่ไม่มีคำสั่งทำลายข้อมูล ไม่ต้องบังคับสำรองก่อนรัน
--     แต่ยังแนบบล็อกย้อนกลับ [Z] ไว้ให้ (comment ปิดไว้) ตามกฎเดียวกัน
--   · รันซ้ำได้ปลอดภัย (`if not exists` ทั้งหมด)
--   · ไม่แตะข้อมูลคลังคำที่มีอยู่แล้วสักแถว (คำเดิมทุกคำ deleted_at = null = ยังใช้งานอยู่ ถูกต้องแล้ว)
--   · ไม่แตะ RLS — ด่านเดิมครบ 4 คำสั่งอยู่แล้ว และการปั๊มตราใช้ UPDATE ซึ่งมีด่านอยู่แล้ว
--
-- ⚠️ ฝั่งเว็บถูกเขียนให้ "ถอยไปทำงานแบบเดิมอัตโนมัติ" ถ้ายังไม่ได้รันไฟล์นี้
--    (ถ้าไม่มีคอลัมน์ deleted_at → sync ยังทำงาน แค่ยังไม่มีการลบข้ามเครื่อง) ไม่พัง ไม่เงียบ
--
